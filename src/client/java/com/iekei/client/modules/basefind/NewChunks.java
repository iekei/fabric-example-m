package com.iekei.client.modules.basefind;

import com.iekei.client.core.Alerts;
import com.iekei.client.core.Render3D;
import com.iekei.client.gui.Module;
import com.iekei.client.gui.Setting;
import java.util.HashSet;
import java.util.Set;
import net.fabricmc.fabric.api.client.rendering.v1.WorldRenderContext;
import net.minecraft.world.phys.AABB;

public final class NewChunks extends Module {
	private static final Setting highlight = Setting.choice("Highlight", "Emerald", "Accent", "Red");
	private static final Set<Long> CHUNKS = new HashSet<>();

	public NewChunks() {
		super("newchunks", "NewChunks", "Marks chunks generated by other players.", false, highlight);
	}

	public static void onChunk(long packed) {
		if (CHUNKS.add(packed)) {
			int x = (int) (packed >> 32);
			int z = (int) packed;
			Alerts.found("New chunk", x * 16 + ", 64, " + z * 16);
		}
	}

	@Override
	public void onRenderWorld(WorldRenderContext ctx) {
		if (CHUNKS.isEmpty()) {
			return;
		}

		var buf = Render3D.lines(ctx);
		int rgb = com.iekei.client.core.Colors.of(mode("Highlight"));

		Render3D.throughWalls(buf, () -> {
			for (long packed : CHUNKS) {
				int x = (int) (packed >> 32);
				int z = (int) packed;
				Render3D.box(ctx.matrixStack(), buf,
						new AABB(x * 16, 0, z * 16, x * 16 + 16, 128, z * 16 + 16), rgb, 0.5F);
			}
		});

		ctx.consumers().endBatch(net.minecraft.client.renderer.RenderType.lines());
	}
}